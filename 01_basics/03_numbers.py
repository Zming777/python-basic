# + - * / 分别表示加、减、乘、除。
# 场景：计算价格，或者把分钟换算成小时和分钟。

print(8 + 3)  # 11
print(8 - 3)  # 5
print(8 * 3)  # 24
print(8 / 3)  # 2.6666666666666665

# // 向下取整；% 取余数。
minutes = 125
print("小时：", minutes // 60)  # 2
print("剩余分钟：", minutes % 60)  # 5
print(-8 // 3)  # -3：向下取整，不是直接删除小数部分。

print(2 ** 3)  # 8：** 表示乘方。
print((2 + 3) * 4)  # 20：括号中的内容先计算。

# 浮点数可能有很小的表示误差。
print(0.1 + 0.2)  # 0.30000000000000004

