# 切片 [开始:结束:步长] 从序列中取出一部分。
# 场景：取前几项、最后几项，或者让序列倒过来。
# 包含开始位置，不包含结束位置；下标从 0 开始。

numbers = [0, 10, 20, 30, 40, 50]
print(numbers[1:4])  # [10, 20, 30]
print(numbers[:3])  # [0, 10, 20]：省略开始位置。
print(numbers[3:])  # [30, 40, 50]：省略结束位置。
print(numbers[-2:])  # [40, 50]：最后两个。
print(numbers[::2])  # [0, 20, 40]：下标每次增加 2，取 0、2、4 位置。
print(numbers[::-1])  # [50, 40, 30, 20, 10, 0]：倒序。

# 字符串也支持切片。
date = "2026-09-14"
print(date[:4])  # 2026
print(date[5:7])  # 09

# 切片边界超出长度没有关系；访问 numbers[100] 则会报错。
print(numbers[:100])  # [0, 10, 20, 30, 40, 50]

